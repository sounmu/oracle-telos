function seeded(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

const KINDS = ["장치", "방법", "시스템", "구조", "조성물"];
const DECISIONS = ["ACCEPTED", "ACCEPTED", "ACCEPTED", "PENDING", "REJECTED", "UNKNOWN"] as const;

async function main() {
  const rand = seeded(2026);
  const pick = <T,>(xs: readonly T[]): T => xs[Math.floor(rand() * xs.length)];
  const out: Record<string, unknown>[] = [];
  let serial = 1;
  for (const f of FIELDS) {
    const members: { id: string; year: number }[] = [];
    for (let k = 0; k < f.count; k += 1) {
      const id = `GEN-${String(serial).padStart(4, "0")}`;
      serial += 1;
      const subject = pick(f.subjects);
      const method = pick(f.methods);
      const effect = pick(f.effects);
      const year = 2008 + Math.floor(rand() * 18);
      const filed = `${year}-${String(1 + Math.floor(rand() * 12)).padStart(2, "0")}-${String(1 + Math.floor(rand() * 28)).padStart(2, "0")}`;
      const cpc = pick(f.cpc);
      const abstract = `${subject}에서 ${method}. 이를 통해 ${effect}.`;
      // 가짜 인용: 같은 분야의 더 오래된 더미 0~3건, 주제 분야는 실제 특허도 가끔 인용
      const older = members.filter((m) => m.year <= year);
      const cites = new Set<string>();
      const n = Math.floor(rand() * 4);
      for (let c = 0; c < n && older.length; c += 1) cites.add(pick(older).id);
      if (f.realTargets && rand() < 0.35) cites.add(pick(f.realTargets));
      out.push({
        id,
        publication: "",
        title: `${subject} ${pick(KINDS)}`,
        decision: pick(DECISIONS),
        cpc,
        cpcLabels: [cpc],
        filed,
        applicant: "(더미)",
        abstract,
        firstClaim: abstract,
        source: "dummy",
        field: f.name,
        cites: [...cites],
      });
      members.push({ id, year });
    }
  }
  await fs.writeFile(OUT, `${JSON.stringify(out, null, 2)}\n`);
  const links = out.reduce((s, p) => s + (p.cites as string[]).length, 0);
  console.log(`더미 ${out.length}건, 가짜 인용 ${links}건 → ${path.relative(process.cwd(), OUT)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
